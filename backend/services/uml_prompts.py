"""Prompt nghiệp vụ dùng chung cho mô hình lớp UML."""


def build_class_diagram_prompt(use_case_context: str, specification_context: str) -> str:
    """Tạo prompt mô hình lớp có đủ thành viên và tên định danh chuẩn UML."""
    return (
        "Bạn là chuyên gia phân tích và thiết kế hướng đối tượng UML. Hãy suy luận "
        "mô hình lớp miền nghiệp vụ từ TOÀN BỘ use case và đặc tả chức năng bên dưới. "
        "Không chỉ trả tên lớp: MỖI lớp bắt buộc phải có ít nhất 2 thuộc tính và 1 phương thức "
        "cụ thể, có căn cứ từ dữ liệu đầu vào. Thuộc tính mô tả dữ liệu/trạng thái mà lớp "
        "quản lý; phương thức mô tả hành vi/nghiệp vụ mà lớp thực hiện. Không dùng các mục "
        "chung chung như 'id', 'data', 'process()', 'handle()' nếu không có căn cứ nghiệp vụ. "
        "Ưu tiên các lớp thực thể và lớp điều khiển nghiệp vụ cần thiết; tránh tạo lớp trùng "
        "nghĩa hoặc lớp framework chung chung. Bao phủ các nghiệp vụ quan trọng trong đầu vào "
        "và tạo quan hệ hợp lý giữa các lớp khi có căn cứ.\n\n"
        "QUY TẮC TÊN ĐỊNH DANH BẮT BUỘC: "
        "Tên lớp dùng tiếng Việt KHÔNG DẤU theo PascalCase, ví dụ SinhVien, PhieuMuon, "
        "ChiTietPhieuMuon. Tên thuộc tính và phương thức dùng tiếng Việt KHÔNG DẤU theo "
        "camelCase, ví dụ maSinhVien, hoTen, ngayMuon, dangNhap(), taoPhieuMuon(). "
        "Không dùng dấu tiếng Việt, dấu cách, dấu gạch nối hoặc tên tiếng Anh nếu nghiệp vụ "
        "có tên tiếng Việt tương ứng. Không đặt cả câu mô tả vào tên thuộc tính/phương thức. "
        "Mỗi thuộc tính là tên định danh ngắn, có thể kèm kiểu dữ liệu như 'maSinhVien: String'; "
        "mỗi phương thức là tên hành động có ngoặc, có thể kèm tham số/kiểu trả về. "
        "Giữ chính xác cùng tên lớp ở hai đầu quan hệ.\n\n"
        "Chỉ trả JSON đúng schema: "
        "{\"classes\":[{\"name\":\"SinhVien\","
        "\"attributes\":[\"maSinhVien: String\",\"hoTen: String\"],"
        "\"methods\":[\"dangNhap()\"]}],"
        "\"relations\":[{\"class_a\":\"SinhVien\",\"class_b\":\"PhieuMuon\","
        "\"relation_type\":\"association|inheritance|composition|aggregation|dependency\"}]}. "
        "Đây là ví dụ định dạng, KHÔNG sao chép máy móc các lớp ví dụ nếu không phù hợp "
        "nghiệp vụ thực tế. Mỗi lớp phải có thuộc tính và phương thức; nếu chưa đủ căn cứ "
        "hãy suy luận tối thiểu từ hành vi được mô tả, không để hai mảng này rỗng. "
        "Nếu không có quan hệ có căn cứ, trả relations là [].\n\n"
        f"USE CASE:\n{use_case_context}\n\nĐẶC TẢ:\n{specification_context}"
    )
